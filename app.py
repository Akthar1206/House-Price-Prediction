import streamlit as st
import pandas as pd
import joblib

# ---------------------------------------
# Page Configuration
# ---------------------------------------

st.set_page_config(
    page_title="House Price Prediction",
    page_icon="🏠",
    layout="centered"
)

# ---------------------------------------
# Load Trained Model
# ---------------------------------------

model_package = joblib.load(
    "models/house_price_model.pkl"
)

model = model_package["model"]
model_name = model_package["model_name"]

# ---------------------------------------
# Title
# ---------------------------------------

st.title("🏠 House Price Prediction")

st.write(
    "Enter the house details below to predict "
    "the estimated house price using Machine Learning."
)

st.info(f"🤖 Model Used: {model_name}")

st.divider()

# ---------------------------------------
# House Details
# ---------------------------------------

st.subheader("🏡 Enter House Details")

col1, col2 = st.columns(2)

with col1:

    area = st.number_input(
        "Area (sq.ft)",
        min_value=100,
        max_value=10000,
        value=1500,
        step=50
    )

    bedrooms = st.number_input(
        "Number of Bedrooms",
        min_value=1,
        max_value=10,
        value=3,
        step=1
    )

    bathrooms = st.number_input(
        "Number of Bathrooms",
        min_value=1,
        max_value=10,
        value=2,
        step=1
    )

    floors = st.number_input(
        "Number of Floors",
        min_value=1,
        max_value=10,
        value=2,
        step=1
    )


with col2:

    year_built = st.number_input(
        "Year Built",
        min_value=1800,
        max_value=2026,
        value=2000,
        step=1
    )

    location = st.selectbox(
        "Location",
        [
            "Downtown",
            "Suburban",
            "Urban",
            "Rural"
        ]
    )

    condition = st.selectbox(
        "House Condition",
        [
            "Excellent",
            "Good",
            "Fair",
            "Poor"
        ]
    )

    garage = st.selectbox(
        "Garage",
        [
            "Yes",
            "No"
        ]
    )

# ---------------------------------------
# Create Input Data
# ---------------------------------------

input_data = pd.DataFrame({
    "Area": [area],
    "Bedrooms": [bedrooms],
    "Bathrooms": [bathrooms],
    "Floors": [floors],
    "YearBuilt": [year_built],
    "Location": [location],
    "Condition": [condition],
    "Garage": [garage]
})

# ---------------------------------------
# Prediction
# ---------------------------------------

st.divider()

if st.button(
    "🔮 Predict House Price",
    use_container_width=True
):

    prediction = model.predict(input_data)[0]

    st.success("Prediction completed successfully! 🎉")

    st.metric(
        "Estimated House Price",
        f"₹ {prediction:,.2f}"
    )

    st.write(
        "The above value is the estimated price "
        "generated by the Machine Learning model."
    )

# ---------------------------------------
# Project Information
# ---------------------------------------

st.divider()

with st.expander("📌 About This Project"):

    st.write("""
    ### House Price Prediction Using Machine Learning

    This project predicts the estimated price of a house
    based on different features such as:

    • Area  
    • Bedrooms  
    • Bathrooms  
    • Floors  
    • Year Built  
    • Location  
    • Condition  
    • Garage  

    Multiple Machine Learning regression algorithms were
    trained and compared before selecting the final model.
    """)


with st.expander("📊 Model Evaluation"):

    st.write("""
    The models were evaluated using:

    • MAE – Mean Absolute Error  
    • RMSE – Root Mean Squared Error  
    • R² Score – Coefficient of Determination  

    Hyperparameter tuning was also performed to improve
    the final model.
    """)

st.caption(
    "🎓 Machine Learning Project – House Price Prediction"
)